// `pnpm ui:audit`: the Paper & Pastel gates (requirements §13.3.3, §13.6).
//  1. contrast.py on the token values the theme really uses (packages/ui/src/theme/tokens.ts), both modes.
//  2. audit.py on every UI source folder: 0 errors required.
// Needs Python 3. Exits non-zero when either gate fails.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { paperPastelTokens } from '../packages/ui/src/theme/tokens.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const skill = join(root, '.claude/skills/paper-pastel-studio/scripts');
const python = process.env.PYTHON ?? 'python3';
// Generated by `astryx theme build` (a token file, like tokens.css, which audit.py also skips).
const GENERATED = new Set([
  'paper-pastel.js',
  'paper-pastel.modules',
  'paper-pastel.css',
  'paper-pastel.d.ts',
]);
const handWritten = (dir) =>
  readdirSync(join(root, dir))
    .filter((name) => !GENERATED.has(name))
    .flatMap((name) => (name === 'theme' ? handWritten(`${dir}/theme`) : [`${dir}/${name}`]));
const UI_SOURCES = [
  'apps/web/src',
  'apps/admin/src',
  ...handWritten('packages/ui/src'),
  'packages/ui/styles',
];

function run(label, args) {
  console.log(`\n== ${label}`);
  const result = spawnSync(python, args, { cwd: root, stdio: 'inherit' });
  if (result.error) throw result.error;
  return result.status === 0;
}

// contrast.py reads `:root` (light) and `.dark` blocks of `--name: H S% L%` declarations.
const block = (selector, tokens) =>
  `${selector} {\n${Object.entries(tokens)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n')}\n}\n`;
const dir = mkdtempSync(join(tmpdir(), 'ui-audit-'));
const tokensFile = join(dir, 'tokens.css');
writeFileSync(
  tokensFile,
  block(':root', paperPastelTokens.light) + block('.dark', paperPastelTokens.dark),
);

let ok;
try {
  ok = run('contrast.py (theme token values, light + dark)', [
    join(skill, 'contrast.py'),
    tokensFile,
    '--fail',
  ]);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
for (const source of UI_SOURCES) {
  ok = run(`audit.py ${source}`, [join(skill, 'audit.py'), source]) && ok;
}

console.log(ok ? '\nui:audit passed' : '\nui:audit FAILED');
process.exit(ok ? 0 : 1);
