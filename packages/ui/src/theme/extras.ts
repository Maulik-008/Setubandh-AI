/**
 * Renders `styles/paper-pastel-extras.css`: the Paper & Pastel identity tokens
 * Astryx has no name for (requirements §13.3.1), exposed as Tailwind utilities
 * with names that do not collide with the Astryx bridge (§13.3.2).
 *
 * Run `pnpm --filter @setubandh/ui theme:build` after changing `tokens.ts`;
 * `test/extras.test.ts` fails while the committed file is stale.
 */
import { CATEGORY_HUES, hsl, paperPastelTokens, type TokenName } from './tokens.ts';

const { light, dark } = paperPastelTokens;

/** Tailwind colour name -> Paper & Pastel token. Utilities: `bg-cta`, `bg-tint-violet`, `text-chip-coral-ink`, ... */
export const EXTRA_COLORS: Record<string, TokenName> = {
  cta: 'cta',
  'cta-foreground': 'cta-foreground',
  ...Object.fromEntries(
    ([0, 1, 2, 3, 4, 5] as const).map((step) => [`surface-${step}`, `surface-${step}` as const]),
  ),
  ...Object.fromEntries(
    CATEGORY_HUES.flatMap((hue) => [
      [`tint-${hue}`, `tint-${hue}` as const],
      [`chip-${hue}`, `accent-${hue}` as const],
      [`chip-${hue}-ink`, `chip-${hue}-ink` as const],
    ]),
  ),
  'input-edge': 'input-edge',
};

export function renderExtrasCss(): string {
  const vars = Object.entries(EXTRA_COLORS).map(
    ([name, token]) => `    --pp-${name}: light-dark(${hsl(light[token])}, ${hsl(dark[token])});`,
  );
  const theme = Object.keys(EXTRA_COLORS).map((name) => `  --color-${name}: var(--pp-${name});`);
  return `/*
 * @generated by \`pnpm --filter @setubandh/ui theme:build\` from src/theme/tokens.ts. Do not edit.
 *
 * Paper & Pastel extras (requirements §13.3.1): tokens Astryx has no name for.
 * Values use light-dark(), so they follow Astryx <Theme mode> in light, dark and
 * system mode alike (Theme sets color-scheme through data-theme on <html>).
 */
@layer theme {
  :root {
${vars.join('\n')}
    /* A chip sitting on a tint: the one sanctioned white / black pair. */
    --pp-on-tint: light-dark(hsl(0 0% 100% / 0.7), hsl(0 0% 0% / 0.2));
  }
}

@theme inline {
${theme.join('\n')}
  --color-on-tint: var(--pp-on-tint);
}
`;
}
